# --------------------------------------------------------------
# Normalization Constant
# --------------------------------------------------------------

def normalization_constant(params):
    """
    Compute

        M = ∫ q(x) dx

    analytically.
    """

    d = params.d

    alpha = params.alpha

    M = (

        d[0]/alpha

        +

        d[1]/alpha**2

        +

        2*d[2]/alpha**3

        +

        6*d[3]/alpha**4

    )

    return M

    # --------------------------------------------------------------
# Unnormalized Kernel
# --------------------------------------------------------------

def unnormalized_kernel(x, params):
    """
    q(x)

    =
    (d1+d2x+d3x²+d4x³)e^(-αx)
    """

    x = np.asarray(x)

    d = params.d

    alpha = params.alpha

    polynomial = (

        d[0]

        +

        d[1]*x

        +

        d[2]*x**2

        +

        d[3]*x**3

    )

    return polynomial*np.exp(-alpha*x)

    # --------------------------------------------------------------
# Normalized Kernel
# --------------------------------------------------------------

def normalized_kernel(x, params):
    """
    φ(x)=q(x)/M
    """

    M = normalization_constant(params)

    return unnormalized_kernel(x, params)/M

# --------------------------------------------------------------
# Triggering Kernel
# --------------------------------------------------------------

def triggering_kernel(x, params):
    """
    g(x)=ηφ(x)
    """

    return params.eta * normalized_kernel(x, params)
