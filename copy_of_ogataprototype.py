# --------------------------------------------------------------

@dataclass
class ClusterParameters:
    """
    Container for transformed clustering parameters.
    """

    d: np.ndarray      # Polynomial coefficients
    alpha: float       # Exponential decay
    eta: float         # Branching ratio


# --------------------------------------------------------------
# Logistic Function
# --------------------------------------------------------------

def logistic(x):

    return 1.0 / (1.0 + np.exp(-x))


# --------------------------------------------------------------
# Parameter Transformation
# --------------------------------------------------------------

def transform_parameters(theta):
    """
    Transform unconstrained optimizer variables into
    admissible clustering parameters.

    Parameters
    ----------
    theta : ndarray (length 6)

        theta =

        [b1,b2,b3,b4,beta,gamma]

    Returns
    -------
    ClusterParameters
    """

    theta = np.asarray(theta, dtype=float)

    if theta.size != 6:
        raise ValueError(
            "theta must contain exactly six parameters."
        )

    # ----------------------------------------------------------
    # Optimizer Variables
    # ----------------------------------------------------------

    b = theta[:4]

    beta = theta[4]

    gamma = theta[5]

    # ----------------------------------------------------------
    # Positive Polynomial Coefficients
    # ----------------------------------------------------------

    d = np.exp(b)

    # ----------------------------------------------------------
    # Positive Exponential Decay
    # ----------------------------------------------------------

    alpha = np.exp(beta)

    # ----------------------------------------------------------
    # Branching Ratio
    # ----------------------------------------------------------

    eta = logistic(gamma)

    # ----------------------------------------------------------
    # Return Parameter Object
    # ----------------------------------------------------------

    return ClusterParameters(
        d=d,
        alpha=alpha,
        eta=eta
    )

