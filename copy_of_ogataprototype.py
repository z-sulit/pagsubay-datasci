# --------------------------------------------------------------
# Elementary Integrals
# --------------------------------------------------------------

def I0(L, alpha):

    return (1.0 - np.exp(-alpha*L))/alpha


def I1(L, alpha):

    e = np.exp(-alpha*L)

    return (1.0 - e*(1.0 + alpha*L))/alpha**2


def I2(L, alpha):

    e = np.exp(-alpha*L)

    return (
        2.0
        -
        e*(2.0 + 2.0*alpha*L + (alpha*L)**2)
    )/alpha**3


def I3(L, alpha):

    e = np.exp(-alpha*L)

    return (
        6.0
        -
        e*(
            6.0
            + 6.0*alpha*L
            + 3.0*(alpha*L)**2
            + (alpha*L)**3
        )
    )/alpha**4

# --------------------------------------------------------------
# Individual Event Compensator
# --------------------------------------------------------------

def event_compensator(L, params):
    """
    Computes

        ∫_0^L g(x) dx

    analytically.
    """

    d = params.d

    alpha = params.alpha

    eta = params.eta

    M = normalization_constant(params)

    integral = (

        d[0]*I0(L, alpha)

        +

        d[1]*I1(L, alpha)

        +

        d[2]*I2(L, alpha)

        +

        d[3]*I3(L, alpha)

    )

    return eta * integral / M


# --------------------------------------------------------------
# Total Cluster Compensator
# --------------------------------------------------------------

def cluster_compensator(event_times, T, params):
    """
    Computes

           T
    ∫ C_M(t) dt
           0

    analytically.
    """

    event_times = np.asarray(event_times, dtype=float)

    total = 0.0

    for tj in event_times:

        L = T - tj

        if L > 0:

            total += event_compensator(L, params)

    return total


