def ogata_loglikelihood(
    lambda_values,
    background_compensator,
    polynomial_compensator,
    fourier_compensator,
    cluster_compensator
):
    """
    Computes the full Ogata log-likelihood.

    Parameters
    ----------
    lambda_values : ndarray

        λ(t_i)

    background_compensator : float

    polynomial_compensator : float

    fourier_compensator : float

    cluster_compensator : float

    Returns
    -------
    loglikelihood : float
    """

    lambda_values = np.asarray(lambda_values, dtype=float)

    if np.any(lambda_values <= 0):

        raise ValueError(
            "Conditional intensity must be strictly positive."
        )

    log_term = np.sum(np.log(lambda_values))

    compensator = (

        background_compensator

        +

        polynomial_compensator

        +

        fourier_compensator

        +

        cluster_compensator

    )

    return log_term - compensator

